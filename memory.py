# ─── Semantic Memory — Persistent Schema Store ────────────────────────────────

SEMANTIC_DB_PATH = "./semantic_memory.db"


def _get_semantic_conn():
    """Returns a connection to the semantic memory database and ensures schema_store table exists."""
    conn = sqlite3.connect(SEMANTIC_DB_PATH)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS schema_store (
            db_path        TEXT PRIMARY KEY,
            schema_version INTEGER NOT NULL,
            full_schema    TEXT NOT NULL,
            stored_at      TEXT NOT NULL
        )
    """)
    conn.commit()
    return conn


def get_full_schema_cached(db_path: str, get_schema_fn) -> str:
    """
    Returns the full database schema from persistent store if valid.
    Uses PRAGMA schema_version to detect schema changes — SQLite increments
    this integer on every CREATE TABLE, DROP TABLE, or ALTER TABLE.
    Falls back to reading from the database and stores the result.

    Args:
        db_path:       path to the SQLite database
        get_schema_fn: function to read full schema from database (get_schema from database.py)

    Returns:
        Full schema string containing all CREATE TABLE statements.
    """
    try:
        # Read current schema version from source database
        src = sqlite3.connect(db_path)
        current_version = src.execute("PRAGMA schema_version;").fetchone()[0]
        src.close()

        conn = _get_semantic_conn()
        row = conn.execute(
            "SELECT schema_version, full_schema FROM schema_store WHERE db_path = ?",
            (db_path,)
        ).fetchone()

        if row and row[0] == current_version:
            print(f"[SEMANTIC MEMORY] Schema cache hit for {db_path} (version {current_version})")
            conn.close()
            return row[1]

        # Cache miss or schema changed — read from source database
        print(f"[SEMANTIC MEMORY] Schema cache miss for {db_path} — reading from database...")
        full_schema = get_schema_fn(db_path)

        conn.execute(
            "INSERT OR REPLACE INTO schema_store VALUES (?, ?, ?, ?)",
            (db_path, current_version, full_schema, datetime.utcnow().isoformat())
        )
        conn.commit()
        conn.close()
        print(f"[SEMANTIC MEMORY] Schema stored for {db_path} (version {current_version})")
        return full_schema

    except Exception as e:
        print(f"[SEMANTIC MEMORY] Schema cache error: {e} — falling back to direct read")
        return get_schema_fn(db_path)


def build_filtered_schema_from_string(full_schema: str, role: str, role_permissions: dict) -> str:
    """
    Filters the full schema string to only permitted tables and columns for the given role.
    No database access needed — parses the CREATE TABLE statements from the schema string directly.
    This replaces build_filtered_schema which required PRAGMA database queries.

    Args:
        full_schema:      complete schema string with all CREATE TABLE statements
        role:             the user role to filter for
        role_permissions: the ROLE_PERMISSIONS dict from query_agent.py

    Returns:
        Filtered schema string containing only permitted tables and columns.
    """
    perms = role_permissions.get(role, {})
    allowed_tables = perms.get("allowed_tables", [])
    allowed_columns = perms.get("allowed_columns", {})

    # Split schema into individual CREATE TABLE blocks
    blocks = _re.split(r'(?=CREATE TABLE)', full_schema.strip(), flags=_re.IGNORECASE)
    schema_parts = []

    for block in blocks:
        block = block.strip()
        if not block:
            continue

        # Extract table name
        match = _re.match(r'CREATE TABLE\s+["\']?(\w+)["\']?', block, _re.IGNORECASE)
        if not match:
            continue
        table_name = match.group(1)

        if table_name not in allowed_tables:
            continue

        permitted = allowed_columns.get(table_name)
        if permitted is None:
            # All columns permitted — keep block as is
            schema_parts.append(block)
            continue

        # Filter to permitted columns only
        lines = block.split('\n')
        filtered_lines = []
        inside_table = False

        for line in lines:
            stripped = line.strip()

            # Always keep the CREATE TABLE header line
            if _re.match(r'CREATE TABLE', stripped, _re.IGNORECASE):
                filtered_lines.append(line)
                inside_table = True
                continue

            # Always keep the closing paren
            if stripped.startswith(')'):
                filtered_lines.append(line)
                continue

            if inside_table:
                # Check if this line defines a permitted column
                col_match = _re.match(r'\s*["\']?(\w+)["\']?\s+\w+', line)
                if col_match:
                    col_name = col_match.group(1)
                    if col_name in permitted:
                        filtered_lines.append(line)
                else:
                    # Table constraint line — keep it
                    filtered_lines.append(line)

        if filtered_lines:
            schema_parts.append('\n'.join(filtered_lines))

    return '\n\n'.join(schema_parts)


def schema_store_count() -> int:
    """Returns the number of databases with cached schemas."""
    try:
        conn = _get_semantic_conn()
        count = conn.execute("SELECT COUNT(*) FROM schema_store").fetchone()[0]
        conn.close()
        return count
    except Exception:
        return 0
